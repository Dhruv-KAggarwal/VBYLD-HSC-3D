/**
 * Group neighbouring weak faces into regions an operator can act on.
 *
 * A recommendation is emitted only when the region's own measurements support
 * the cause it addresses.
 */

import { UnionFind, buildTopology } from '../meshdata.mjs';
import { applyMatrix } from '../glbmesh.mjs';
import { readRecord, UNKNOWN } from './scoring.mjs';

const CAUSE_SHARE = 0.4;

const CAUSES = {
  noCameras: 'No registered camera sees this surface',
  occluded: 'The surface is mostly hidden behind other geometry',
  grazing: 'Seen only at very shallow angles',
  fewCameras: 'Seen by fewer than three cameras',
  lowDiversity: 'All views come from nearly the same direction',
  highReprojection: 'High reprojection error in nearby features',
  lowSupport: 'Few dense points lie on the surface',
  blurry: 'Observing frames are comparatively soft',
  generated: 'Geometry was generated by mesh repair',
};

function recommendations(causes, facing, away) {
  const has = (key) => causes.some((c) => c.key === key);
  const out = [];
  if (has('generated')) out.push('Capture this area to replace estimated geometry with observations.');
  if (has('noCameras') && away) out.push('Capture the opposite side: this surface faces away from every flight position.');
  else if (has('noCameras') || has('occluded')) out.push('Capture the occluded surfaces from additional positions that have a clear line of sight.');
  if (has('grazing')) {
    out.push(facing === 'vertical'
      ? 'Capture additional oblique footage, with the camera tilted towards this facade.'
      : 'Fly higher or tilt the camera down so this surface is seen more directly.');
  }
  if (has('fewCameras')) out.push('Improve image overlap here: fly slower or add another pass.');
  if (has('lowDiversity')) out.push('Increase viewpoint diversity, for example by orbiting the structure or flying at a second height.');
  if (has('blurry')) out.push('Reduce motion blur: fly slower or use a faster shutter.');
  if (has('highReprojection')) out.push('Feature positions disagree here; steadier footage with more overlap would constrain it better.');
  if (has('lowSupport') && !has('noCameras') && !has('fewCameras') && !has('grazing') && !has('blurry')) {
    out.push('Dense matching found little despite adequate views; the surface may be reflective, transparent or textureless.');
  }
  return out;
}

/**
 * @param {Buffer} records       confidence records for this mesh
 * @param {object} samples       faceSamples(mesh)
 * @param {Uint16Array|null} occluded  per-face occluded camera counts
 */
export function findLowRegions({
  context, mesh, records, samples, occluded = null, grazing = null, views = [], videoIds = [], threshold = 40, maxRegions = 150,
}) {
  const faces = samples.faces;
  const weak = new Uint8Array(faces);
  let total = 0;
  for (let f = 0; f < faces; f += 1) {
    const { score } = readRecord(records, f);
    weak[f] = score === UNKNOWN || score < threshold ? 1 : 0;
    total += samples.area[f];
  }
  const topology = buildTopology(mesh);
  const sets = new UnionFind(faces);
  for (let e = 0; e < topology.edgeCount; e += 1) {
    let first = -1;
    for (let i = topology.edgeStart[e]; i < topology.edgeStart[e + 1]; i += 1) {
      const f = (topology.edgeHalves[i] / 3) | 0;
      if (!weak[f]) continue;
      if (first < 0) first = f; else sets.union(first, f);
    }
  }
  const groups = new Map();
  for (let f = 0; f < faces; f += 1) {
    if (!weak[f]) continue;
    const root = sets.find(f);
    let group = groups.get(root);
    if (!group) { group = { area: 0, faces: [] }; groups.set(root, group); }
    group.area += samples.area[f];
    group.faces.push(f);
  }
  const metres = context.metresPerUnit;
  // Ignore speckle: a region must be at least 0.05% of the surface.
  const kept = [...groups.values()].filter((g) => g.area >= total * 0.0005 && g.faces.length >= 8)
    .sort((a, b) => b.area - a.area);
  const meanCamera = [0, 1, 2].map((k) => views.reduce((s, v) => s + v.center[k], 0) / Math.max(1, views.length));

  const regions = kept.slice(0, maxRegions).map((group, index) => {
    const min = [Infinity, Infinity, Infinity];
    const max = [-Infinity, -Infinity, -Infinity];
    const centre = [0, 0, 0];
    const normal = [0, 0, 0];
    const share = Object.fromEntries(Object.keys(CAUSES).map((k) => [k, 0]));
    const provenance = [0, 0, 0, 0, 0, 0];
    let scoreSum = 0;
    let scoredArea = 0;
    let minimum = null;
    let cameraSum = 0;
    let mask = 0;
    for (const f of group.faces) {
      const a = samples.area[f];
      const r = readRecord(records, f);
      for (let k = 0; k < 3; k += 1) {
        const v = mesh.indices[f * 3 + k] * 3;
        for (let axis = 0; axis < 3; axis += 1) {
          min[axis] = Math.min(min[axis], mesh.positions[v + axis]);
          max[axis] = Math.max(max[axis], mesh.positions[v + axis]);
        }
      }
      for (let k = 0; k < 3; k += 1) {
        centre[k] += samples.centroid[f * 3 + k] * a;
        normal[k] += samples.normal[f * 3 + k] * a;
      }
      if (r.score !== UNKNOWN) {
        scoreSum += r.score * a;
        scoredArea += a;
        minimum = minimum == null ? r.score : Math.min(minimum, r.score);
      }
      provenance[r.provenance] += a;
      mask |= r.videoMask;
      const generated = r.provenance === 3 || r.provenance === 4;
      if (generated) { share.generated += a; continue; }
      const cameras = r.cameras ?? 0;
      cameraSum += cameras * a;
      const hidden = occluded ? occluded[f] : 0;
      const shallow = grazing ? grazing[f] : 0;
      if (r.cameras === 0) {
        if (shallow > 0) share.grazing += a;
        else if (hidden > 0) share.occluded += a;
        else share.noCameras += a;
      } else {
        if (cameras < 3) share.fewCameras += a;
        if (cameras >= 2 && r.spread != null && r.spread < 5) share.lowDiversity += a;
        if (r.incidence != null && r.incidence > 65) share.grazing += a;
        if (hidden > cameras * 3) share.occluded += a;
      }
      if (r.reprojectionError != null && r.reprojectionError > 1.4) share.highReprojection += a;
      if (r.support != null && r.support < 35) share.lowSupport += a;
      if (r.quality != null && r.quality < 45) share.blurry += a;
    }
    for (let k = 0; k < 3; k += 1) centre[k] /= group.area || 1;
    const length = Math.hypot(...normal) || 1;
    const unit = normal.map((v) => v / length);
    const upness = Math.abs(unit[0] * context.up[0] + unit[1] * context.up[1] + unit[2] * context.up[2]);
    const facing = upness > 0.7 ? 'horizontal' : upness < 0.45 ? 'vertical' : 'sloped';
    const away = views.length > 0
      && unit[0] * (meanCamera[0] - centre[0]) + unit[1] * (meanCamera[1] - centre[1]) + unit[2] * (meanCamera[2] - centre[2]) < 0;
    const causes = Object.entries(share)
      .map(([key, area]) => ({ key, label: CAUSES[key], areaShare: Math.round((area / group.area) * 100) / 100 }))
      .filter((c) => c.areaShare >= CAUSE_SHARE)
      .sort((a, b) => b.areaShare - a.areaShare);

    // World-space (viewer) box from the eight local corners.
    const corners = new Float32Array(24);
    for (let i = 0; i < 8; i += 1) corners.set([0, 1, 2].map((k) => ((i >> k) & 1 ? max[k] : min[k])), i * 3);
    const world = Float32Array.from(centre);
    if (mesh.rootMatrix) {
      applyMatrix(corners, mesh.rootMatrix, 1);
      applyMatrix(world, mesh.rootMatrix, 1);
    }
    const box = { min: [Infinity, Infinity, Infinity], max: [-Infinity, -Infinity, -Infinity] };
    for (let i = 0; i < 24; i += 1) {
      box.min[i % 3] = Math.min(box.min[i % 3], corners[i]);
      box.max[i % 3] = Math.max(box.max[i % 3], corners[i]);
    }
    const worldNormal = Float32Array.from(unit);
    if (mesh.rootMatrix) applyMatrix(worldNormal, mesh.rootMatrix, 0);
    const wl = Math.hypot(...worldNormal) || 1;
    return {
      id: `region_${String(index + 1).padStart(3, '0')}`,
      faceCount: group.faces.length,
      areaM2: Math.round(group.area * metres * metres * 100) / 100,
      surfacePercent: Math.round((group.area / total) * 10000) / 100,
      boundingBox: box,
      centre: [...world],
      normal: [...worldNormal].map((v) => v / wl),
      orientation: facing,
      averageConfidence: scoredArea ? Math.round(scoreSum / scoredArea) : null,
      minimumConfidence: minimum,
      unknownPercent: Math.round((1 - scoredArea / group.area) * 100),
      meanSupportingCameras: Math.round((cameraSum / group.area) * 10) / 10,
      supportingVideos: videoIds.filter((_, i) => mask & (1 << i)),
      provenancePercent: provenance.map((a) => Math.round((a / group.area) * 100)),
      causes,
      recommendations: recommendations(causes, facing, away),
    };
  });
  return {
    threshold,
    totalRegions: kept.length,
    listedRegions: regions.length,
    ignoredFragments: groups.size - kept.length,
    boundingBoxFrame: 'viewer world coordinates (Y up)',
    areaUnits: context.scaleReliable ? 'square metres' : 'square metres at an unverified scale',
    regions,
  };
}
